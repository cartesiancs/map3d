import { geometryQuery, layerGroups } from '../src/data/layers.ts';
import { isQueryFailure, serviceBackoff } from '../src/data/mapFailures.ts';

const endpoints = ['https://overpass-api.de/api/interpreter', 'https://overpass.private.coffee/api/interpreter'];
const agent = 'Map3dStudio/1.0 (+https://github.com/elenichas/map3d)';
const maxBytes = 65536;
type Cache = { match(request: Request): Promise<Response | undefined>; put(request: Request, response: Response): Promise<void> };
type Options = { fetch?: typeof fetch; cache?: Cache; now?: () => number; wait?: (ms: number) => Promise<void>; provider?: string; apiKey?: string };
export type MapDataEnvironment = { MAP_DATA_PROVIDER?: string; OVERPASS_CH_API_KEY?: string };
const json = (body: unknown, status = 200, headers: Record<string, string> = {}) => Response.json(body, { status, headers: { 'Cache-Control': 'no-store', ...headers } });

/** Accept only the bounded, read-only queries generated by this application. */
export function validSceneQuery(query: string) {
  if (new TextEncoder().encode(query).length > maxBytes) return false;
  const polygon = query.match(/\(poly:"([\d.eE\s+-]+)"\)/)?.[1];
  if (!polygon) return false;
  const coordinates = polygon.split(/\s+/).map(Number);
  if (coordinates.length < 6 || coordinates.length % 2 || coordinates.some((n, i) => !Number.isFinite(n) || Math.abs(n) > (i % 2 ? 180 : 90))) return false;
  const points = Array.from({ length: coordinates.length / 2 }, (_, i) => ({ lat: coordinates[i * 2], lng: coordinates[i * 2 + 1] }));
  return geometryQuery(points) === query || layerGroups.some(group => geometryQuery(points, group.id) === query || group.selectors.some((_, index) => geometryQuery(points, group.id, index) === query));
}

export function createMapProxy(options: Options = {}) {
  const apiKey = options.apiKey?.trim() || '';
  const provider = options.provider || (apiKey ? 'overpass-ch' : 'public');
  const managed = provider === 'overpass-ch';
  const configurationError = !['public','overpass-ch'].includes(provider) ? 'The map-data provider setting is invalid.' : managed && (!apiKey || /[\r\n]/.test(apiKey)) ? 'The overpass.ch API key is missing or invalid in the server configuration.' : '';
  const fetchData = options.fetch || ((...args: Parameters<typeof fetch>) => globalThis.fetch(...args)), now = options.now || Date.now;
  const wait = options.wait || ((ms: number) => new Promise<void>(resolve => setTimeout(resolve, ms)));
  const servers = (managed ? ['https://api.overpass.ch/v1/interpreter'] : endpoints).map(url => ({ url, notBefore: 0, failures: 0 }));
  const pending = new Map<string, {controller:AbortController; task:Promise<Response>; users:number}>();
  let preferred = 0, nextRequestAt = 0;
  let active = 0, blocked: {until:number; message:string} | undefined;
  const permanentError = (error:string) => json({error,retryable:false,canSplit:false,retryScope:'configuration'},503);
  async function load(query: string, cacheKey: Request, signal:AbortSignal, cache?: Cache) {
    const failures: { server: string; status: number | string; detail?:string; scope:'query'|'service' }[] = [];
    for (const index of servers.map((_,offset)=>(preferred+offset)%servers.length)) {
      signal.throwIfAborted();
      const server = servers[index];
      if (server.notBefore > now()) continue;
      const start = Math.max(nextRequestAt, now()); nextRequestAt = start + (managed ? 2100 : 750);
      if (start > now()) await wait(start - now());
      signal.throwIfAborted();
      const controller = new AbortController(), timer = setTimeout(() => controller.abort(), 35000);
      const startedAt = now();
      // Correlate failures without logging the user's boundary or raw query.
      const diagnostic = {server:new URL(server.url).hostname,queryId:cacheKey.url.split('/').pop()!.slice(0,16)};
      const cancel=()=>controller.abort(signal.reason);
      signal.addEventListener('abort',cancel,{once:true});
      let receivedResponse = false, queryFailure = false;
      try {
        // Browsers cannot reliably set an app User-Agent. Do not forward their Origin
        // or Referer: identify this service explicitly and use standard form encoding.
        const response = await fetchData(server.url, { method: 'POST', headers: { 'User-Agent': agent, Accept: 'application/json', 'Content-Type': 'application/x-www-form-urlencoded;charset=UTF-8', ...(managed ? {'X-API-Key':apiKey} : {}) }, body: new URLSearchParams({ data: query }).toString(), signal: controller.signal, redirect: 'manual' });
        receivedResponse = true;
        signal.throwIfAborted();
        if (!response.ok) {
          const raw=(await response.text());
          const detail=raw.replace(/<[^>]*>/g,' ').replace(/\s+/g,' ').trim().slice(0,300);
          signal.throwIfAborted();
          queryFailure = isQueryFailure(response.status, detail);
          failures.push({ server: new URL(server.url).hostname, status: response.status, detail:managed?undefined:detail, scope:queryFailure?'query':'service' });
          console.warn('Map-data upstream HTTP failure', JSON.stringify({...diagnostic,status:response.status,elapsedMs:now()-startedAt,scope:queryFailure?'query':'service',ray:response.headers.get('cf-ray'),errorType:response.headers.get('cf-error-type'),errorOrigin:response.headers.get('cf-error-origin')}));
          let code='';
          if(managed) {try {code=JSON.parse(raw).error;} catch {/* Overpass also returns HTML errors. */}}
          if(managed && ([401,403].includes(response.status) || code==='quota_exceeded')) {
            const message=code==='key_scope' ? 'overpass.ch requires an All APIs key for geometry queries. The site owner needs to replace the Maps-only server key.' : code==='quota_exceeded' ? 'The overpass.ch monthly allowance has been reached. Loaded layers are kept. The site owner can check the data plan.' : response.status===401 ? 'overpass.ch rejected the server API key. The site owner needs to check the key.' : 'overpass.ch denied access. The site owner needs to check the key restrictions and plan.';
            blocked={until:now()+300000,message};
            return permanentError(message);
          }
          if (response.status === 400) return json({ error: 'The map server rejected this query (HTTP 400).' }, 400);
          const retry = response.headers.get('Retry-After'), seconds = Number(retry);
          const retryMs = retry ? Number.isFinite(seconds) ? seconds * 1000 : Math.max(0, Date.parse(retry) - now()) || 0 : 0;
          if (!queryFailure) server.failures++;
          // Query resource limits are local to this job; outages cool the service.
          server.notBefore = now() + Math.max(retryMs, queryFailure ? 2000 : serviceBackoff(server.failures, response.status));
          continue;
        }
        const data = await response.json() as { elements?: unknown[]; remark?: string } | null;
        signal.throwIfAborted();
        if (!data || !Array.isArray(data.elements) || data.remark) {
          queryFailure = isQueryFailure(200, data?.remark);
          throw Error(data?.remark?.slice(0,300) || 'incomplete response');
        }
        preferred = index; server.notBefore = 0; server.failures = 0;
        const result = json(data, 200, { 'Cache-Control': 'public, max-age=900', 'X-Map-Cache': 'MISS', 'X-Map-Source': new URL(server.url).hostname });
        if (cache) { try { await cache.put(cacheKey, result.clone()); } catch { /* A cache failure must not discard valid map data. */ } }
        return result;
      } catch (error) {
        signal.throwIfAborted();
        console.error('Map-data upstream transport failure', JSON.stringify({...diagnostic,elapsedMs:now()-startedAt,phase:receivedResponse?'response':'connection',timedOut:controller.signal.aborted,scope:queryFailure?'query':'service'}));
        failures.push({ server: new URL(server.url).hostname, status: controller.signal.aborted ? 'timeout' : receivedResponse ? 'incomplete response' : 'connection failure', detail:managed?undefined:error instanceof Error?error.message.slice(0,300):'Unknown failure', scope:queryFailure?'query':'service' });
        if (!queryFailure) server.failures++;
        server.notBefore = now() + (queryFailure ? 2000 : serviceBackoff(server.failures));
      } finally { clearTimeout(timer); signal.removeEventListener('abort',cancel); }
    }
    signal.throwIfAborted();
    preferred = (preferred + 1) % servers.length;
    const seconds = Math.max(2, Math.ceil((Math.min(...servers.map(server => server.notBefore)) - now()) / 1000));
    const detail = failures.map(failure => `${failure.server}: ${typeof failure.status === 'number' ? 'HTTP ' : ''}${failure.status}`).join('; ');
    const canSplit=failures.some(failure=>failure.scope==='query');
    return json({ retryScope: canSplit ? 'query' : 'service', canSplit, attempted:failures.length>0, error: detail ? `Map-data services could not complete this request (${detail}).` : 'Map-data services are cooling down before the next automatic retry.', failures }, 503, { 'Retry-After': String(seconds) });
  }
  return async function handle(request: Request) {
    const url = new URL(request.url);
    // Older Pages runtimes may not expose incoming disconnect signals.
    const signal=request.signal || new AbortController().signal;
    const origin = request.headers.get('Origin');
    if (origin && origin !== url.origin) return json({ error: 'This endpoint accepts requests from this app only.' }, 403);
    if (request.method !== 'POST') return json({ error: 'Use POST to load map geometry.' }, 405, { Allow: 'POST' });
    if (Number(request.headers.get('Content-Length')) > maxBytes) return json({ error: 'This boundary has too many vertices. Simplify its outline.' }, 413);
    const query = (await request.text()).trim();
    if (!validSceneQuery(query)) return json({ error: 'Invalid map query. Draw a boundary and try again.' }, 400);
    if(configurationError) return permanentError(configurationError);
    const digest = await crypto.subtle.digest('SHA-256', new TextEncoder().encode(query));
    const hash = Array.from(new Uint8Array(digest), byte => byte.toString(16).padStart(2, '0')).join('');
    const cacheKey = new Request(`${url.origin}/__map-cache/v2/${provider}/${hash}`);
    const cache = options.cache || (globalThis as unknown as { caches?: { default?: Cache } }).caches?.default;
    if (cache) {
      try {
        const cached = await cache.match(cacheKey);
        if (cached) { const result = new Response(cached.body, cached); result.headers.set('X-Map-Cache', 'HIT'); return result; }
      } catch { /* Loading still works when the cache is unavailable. */ }
    }
    signal.throwIfAborted();
    if(blocked && blocked.until>now()) return permanentError(blocked.message);
    let entry = pending.get(query);
    if (!entry || entry.controller.signal.aborted) {
      if(managed && active) return json({retryScope:'service',retryable:true,attempted:false,canSplit:false,error:'A map-data request is already running. Waiting to retry automatically.'},503,{'Retry-After':'3'});
      const controller=new AbortController();
      active++;
      entry={controller,task:load(query,cacheKey,controller.signal,cache).finally(()=>{active--;}),users:0};
      pending.set(query,entry);
      const own=entry;
      void entry.task.finally(()=>{if(pending.get(query)===own) pending.delete(query);}).catch(()=>{});
    }
    entry.users++;
    const own=entry;
    let released=false;
    const release=()=>{
      if(released)return;released=true;own.users--;
      if(own.users===0){own.controller.abort();if(pending.get(query)===own)pending.delete(query);}
    };
    let cancel=()=>{};
    const aborted=new Promise<never>((_,reject)=>{cancel=()=>{release();reject(signal.reason);};signal.addEventListener('abort',cancel,{once:true});});
    try { return (await Promise.race([own.task,aborted])).clone(); }
    finally { signal.removeEventListener('abort',cancel); release(); }

  };
}

export function createEnvironmentMapProxy(options:Options={}) {
  let key='',provider='',handle:ReturnType<typeof createMapProxy>;
  return (request:Request,env:MapDataEnvironment={})=>{
    if(!handle || key!==(env.OVERPASS_CH_API_KEY || '') || provider!==(env.MAP_DATA_PROVIDER || '')) {
      key=env.OVERPASS_CH_API_KEY || '';provider=env.MAP_DATA_PROVIDER || '';
      handle=createMapProxy({...options,apiKey:key,provider});
    }
    return handle(request);
  };
}
const handle = createEnvironmentMapProxy();
export default {
  fetch(request: Request, env: MapDataEnvironment & { ASSETS: { fetch(request: Request): Promise<Response> } }) {
    return new URL(request.url).pathname === '/api/interpreter' ? handle(request,env) : env.ASSETS.fetch(request);
  },
};
